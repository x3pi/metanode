#!/usr/bin/env python3
"""
Summarize durability test results from CSV into verifiable Markdown table.
Strict Anti-Fabrication: reads solely from CSV output generated by run_logged.sh.
"""

import csv
import os
import sys

def parse_csv(csv_path):
    if not os.path.isfile(csv_path):
        print(f"❌ [ERROR] Summary CSV not found: {csv_path}", file=sys.stderr)
        sys.exit(1)

    rows = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)
    return rows

def generate_markdown(rows, evidence_id="durability_20rounds_expanded"):
    total_rounds = len(rows)
    pass_count = sum(1 for r in rows if r["Verdict"] == "PASS")
    fail_count = sum(1 for r in rows if "FAIL" in r["Verdict"])
    inconclusive_count = sum(1 for r in rows if "INCONCLUSIVE" in r["Verdict"])

    lines = []
    lines.append("| Vòng | Mục tiêu bị `kill -9` | Delay | Kill Phase | Quorum Pause | Exit Code | Sentinel | H_before | Block kiểm tra | Block Hash | State Root | Kết quả | Evidence |")
    lines.append("| :---: | :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |")

    for r in rows:
        vong = f"**R{r['Round']}**"
        targets = r['TargetNodes']
        if "val0" in targets and len(targets.split()) == 1:
            targets_fmt = "`val0` *(Leader)*"
        elif len(targets.split()) >= 2:
            targets_fmt = f"`{targets}` *(Dual)*"
        else:
            targets_fmt = f"`{targets}`"

        delay = r['KillTiming']
        phase = r.get('CommitPhase', 'unknown')
        q_pause = r.get('QuorumPause', 'N/A')
        exit_code = r.get('RestartExitCode', '0')
        sentinel = r.get('IntegritySentinel', 'None')
        h_before = f"#{r.get('H_before', '0')}"
        check_blk = f"#{r.get('CheckBlock', '0')}"
        b_hash = f"`{r.get('BlockHash', '')}`"
        s_root = f"`{r.get('StateRoot', '')}`"
        verdict = f"**{r.get('Verdict', 'INCONCLUSIVE')}**"
        ev_tag = f"`evidence:{evidence_id}`"

        lines.append(f"| {vong} | {targets_fmt} | {delay} | {phase} | {q_pause} | {exit_code} | {sentinel} | {h_before} | {check_blk} | {b_hash} | {s_root} | {verdict} | {ev_tag} |")

    table_md = "\n".join(lines)
    return table_md, total_rounds, pass_count, fail_count, inconclusive_count

def main():
    csv_path = sys.argv[1] if len(sys.argv) > 1 else "/tmp/crash_recovery_20rounds_summary.log"
    evidence_id = sys.argv[2] if len(sys.argv) > 2 else "durability_20rounds_expanded"

    rows = parse_csv(csv_path)
    table_md, total, passed, failed, incon = generate_markdown(rows, evidence_id)

    print(f"--- SUMMARY ({total} Rounds) ---")
    print(f"PASS: {passed}, FAIL: {failed}, INCONCLUSIVE: {incon}\n")
    print(table_md)

if __name__ == "__main__":
    main()
